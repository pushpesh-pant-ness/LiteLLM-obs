#!/usr/bin/env bash
# Apply bootstrap/tenants.json everywhere. Run after editing it (new team, budget, key, model).
#
#   1. LiteLLM: orgs/teams/budgets/keys/limits + scoped read roles (bootstrap.py)
#   2. Postgres: reporting views + scoped roles/schemas (db-setup)
#   3. Grafana: one org per team and per org, scoped datasource, Cost dashboard (tenant_access.py)
#      Langfuse: one org + project per team, project key, viewers (tenant_access.py)
#   4. Local test users in Langfuse (only if CREATE_TEST_USERS=true; sign-up is opened briefly)
#   5. LiteLLM again: team callbacks now point at each team's own Langfuse project
#   6. Alertmanager: per-team alert routes (tenant_alerts.py)
# Idempotent. Then run ./scripts/verify.sh. (scripts/setup.sh runs this for you.)
# Attach mode: step 1 only adds team metadata + callbacks (tenants: observe), step 2 targets the
# production database (or writes postgres/generated/dba/dba-apply.sql with database.setup: manual).
set -euo pipefail
cd "$(dirname "$0")/.."
export MSYS_NO_PATHCONV=1
run_py() { docker compose run --rm --no-deps -T ${MISSING:+-e MISSING="$MISSING"} --entrypoint python bootstrap -u "$@" 2>&1 | { grep -v -E '^ ?Container ' || true; }; }
wait_langfuse() {  # the container is "up" long before the Next.js app answers
  local host; host=$(envval BIND_ADDRESS); [[ -z "$host" || "$host" == 0.0.0.0 ]] && host=localhost
  for _ in $(seq 1 100); do   # up to 5 min (first boot migrates)
    curl -sf "http://$host:$(envval LANGFUSE_PORT | grep . || echo 3000)/api/public/health" >/dev/null 2>&1 && return 0
    sleep 3
  done
  echo "  ! Langfuse did not become ready"; return 1
}
envval() { { grep -E "^$1=" .env 2>/dev/null || true; } | cut -d= -f2-; }
TEST_USERS=$(envval CREATE_TEST_USERS); TEST_USERS=${TEST_USERS:-true}
AM_PORT=$(envval ALERTMANAGER_PORT); AM_PORT=${AM_PORT:-9093}

echo "######## 1/6 LiteLLM teams, keys, limits"
docker compose run --rm -T bootstrap 2>&1 | { grep -v -E '^ ?Container ' || true; }

echo; echo "######## 2/6 Postgres reporting views + scoped roles"
if [[ "$(envval DB_SETUP)" == "manual" ]]; then
  mkdir -p postgres/generated/dba
  out=postgres/generated/dba/dba-apply.sql
  { echo "-- GENERATED by scripts/apply-tenants.sh - contains passwords, do not commit or e-mail in clear."
    echo "-- Run as a role with CREATEROLE and CREATE on the LiteLLM database:"
    echo "--   psql \"host=... dbname=$(envval LITELLM_DB_NAME) user=...\" -v ON_ERROR_STOP=1 -f dba-apply.sql"
    echo "-- Re-run it after every team change (scripts/apply-tenants.sh regenerates it)."
    echo "\set ro_pw '$(envval GRAFANA_RO_DB_PASSWORD)'"
    for f in postgres/sql/*.sql postgres/generated/*.sql; do [[ -f "$f" ]] && { echo; echo "-- ==== $f"; cat "$f"; }; done
  } > "$out"
  echo "  database.setup is manual: give $out to your DBA (reporting views, grafana_ro, one role per team/org)"
else
  docker compose --profile db-setup up --no-deps db-setup 2>&1 | grep -E 'db-setup:|ERROR|FATAL|error' || true
fi

echo; echo "######## 3/6 Grafana orgs + Langfuse orgs/projects"
wait_langfuse   # first boot of a new server: Langfuse runs its migrations before it answers
run_py tenant_access.py

MEMBERS=$(envval MEMBER_ACCOUNTS); MEMBERS=${MEMBERS:-local}
if [[ "$TEST_USERS" == "true" || "$MEMBERS" == "local" ]]; then
  echo; echo "######## 4/6 Langfuse local accounts (members / test viewers)"
  missing=$(run_py - <<'EOF'
import json, os, langfuse_admin as la
if not os.path.exists("test-users.json"): raise SystemExit
for login, u in json.load(open("test-users.json")).items():
    try:
        la.LangfuseAdmin("http://langfuse-web:3000", u.get("email") or f"{login}@example.com", u["password"])
    except RuntimeError:
        print(login)
EOF
)
  if [[ -n "$missing" ]]; then
    echo "  creating: $(echo $missing)  (sign-up opened briefly)"
    LANGFUSE_DISABLE_SIGNUP=false docker compose --profile traces up -d langfuse-web >/dev/null 2>&1; wait_langfuse
    MISSING="$missing" run_py - <<'EOF'
import json, os, urllib.request
missing = set(os.environ.get("MISSING", "").split())
for login, u in json.load(open("test-users.json")).items():
    if login not in missing:
        continue
    body = json.dumps({"name": u.get("name") or login, "email": u.get("email") or f"{login}@example.com", "password": u["password"]}).encode()
    r = urllib.request.Request("http://langfuse-web:3000/api/auth/signup", data=body, method="POST",
                               headers={"Content-Type": "application/json"})
    try:
        urllib.request.urlopen(r, timeout=30); print(f"  {login}: created")
    except urllib.error.HTTPError as e:
        print(f"  {login}: {e.code} {e.read().decode()[:80]}")
EOF
    docker compose --profile traces up -d langfuse-web >/dev/null 2>&1; wait_langfuse
    echo "  sign-up closed again"
    run_py tenant_access.py --langfuse-only
  else
    echo "  all test users exist"
  fi
fi

echo; echo "######## 5/6 LiteLLM team callbacks -> team Langfuse projects"
docker compose run --rm -T bootstrap 2>&1 | grep -E 'traces ->|Error|Traceback' || true

echo; echo "######## 6/6 Alertmanager per-team routes"
run_py tenant_alerts.py
docker compose exec -T alertmanager amtool check-config /etc/alertmanager/alertmanager.yml | tail -2
curl -s -X POST "http://localhost:$AM_PORT/-/reload" >/dev/null && echo "  Alertmanager reloaded"

echo; echo "Done. Run ./scripts/verify.sh"
