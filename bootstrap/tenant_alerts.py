"""Generate alertmanager/alertmanager.yml from tenants.json (run by scripts/apply-tenants.sh).

Every alert goes to the platform channel (#llm-alerts). Alerts that carry a team_alias label
(budget, error rate) ALSO go to that team's channel, so each team hears about its own problems.

Per team, in tenants.json (optional):  "alerts": {"slack_channel": "#team-search-alerts"}
Webhook URLs are secrets: alertmanager/slack_webhook_url (platform) and alertmanager/slack/<team>.url
(placeholders are created; git-ignored).
"""

import json
import os

TENANTS = os.environ.get("TENANTS_FILE", "tenants.json")
AM_DIR = os.environ.get("ALERTMANAGER_DIR", "/alertmanager")
PLACEHOLDER = "https://hooks.slack.com/services/REPLACE/ME/PLACEHOLDER\n"

TEXT = """        title: '{{ if eq .Status "firing" }}:rotating_light:{{ else }}:white_check_mark:{{ end }} {{ .CommonLabels.alertname }} ({{ .Status }})'
        text: |-
          {{ range .Alerts }}*{{ .Annotations.summary }}*
          {{ .Annotations.description }}
          {{ end }}"""


def main():
    with open(TENANTS, encoding="utf-8") as f:
        cfg = json.load(f)
    teams = [t for o in cfg["orgs"] for t in o.get("teams", [])]
    os.makedirs(f"{AM_DIR}/slack", exist_ok=True)
    out = [
        "# GENERATED by bootstrap/tenant_alerts.py from tenants.json - edit tenants.json, then run",
        "# scripts/apply-tenants.sh. Webhook URLs live in git-ignored files next to this one.",
        "global:",
        "  slack_api_url_file: /etc/alertmanager/slack_webhook_url",
        "  resolve_timeout: 5m",
        "",
        "route:",
        "  receiver: platform",
        '  group_by: ["alertname", "team_alias", "model"]',
        "  group_wait: 30s",
        "  group_interval: 5m",
        "  repeat_interval: 4h",
        "  routes:",
        "    # 1) everything -> platform channel, then keep matching",
        "    - receiver: platform",
        "      continue: true",
    ]
    for t in teams:
        out += [f"    # 2) {t['alias']} alerts -> the team's own channel",
                f"    - receiver: {t['alias']}",
                f'      matchers: [\'team_alias="{t["alias"]}"\']']
    out += ["", "receivers:", "  - name: platform", "    slack_configs:", '      - channel: "#llm-alerts"',
            "        send_resolved: true", TEXT]
    for t in teams:
        channel = (t.get("alerts") or {}).get("slack_channel") or f"#llm-alerts-{t['alias'][len('team-'):]}"
        url_file = f"{AM_DIR}/slack/{t['alias']}.url"
        if not os.path.exists(url_file):
            with open(url_file, "w", encoding="utf-8") as f:
                f.write(PLACEHOLDER)
        out += [f"  - name: {t['alias']}", "    slack_configs:",
                f"      - api_url_file: /etc/alertmanager/slack/{t['alias']}.url",
                f'        channel: "{channel}"', "        send_resolved: true", TEXT]
    with open(f"{AM_DIR}/alertmanager.yml", "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"  alertmanager.yml: platform + {len(teams)} team routes "
          f"({', '.join(t['alias'] for t in teams)}); webhook placeholders in alertmanager/slack/")


if __name__ == "__main__":
    main()
